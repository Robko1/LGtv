/*
 * A normalizálás PONTOSAN ugyanaz, mint az epgGuide.normalizeName (különben a
 * táblakulcsok nem találnának): kisbetű, ékezetek levétele, [..] kidobása,
 * minősítő szavak (uhd/hd/…) levétele, minden nem betű/szám kidobása.
 */
function normalizeEpgName(value: string): string {
  return String(value || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\[[^\]]*\]/g, ' ')
    .replace(/\b(uhd|fhd|hd|sd|4k|hevc|h265|h264)\b/g, ' ')
    .replace(/[^a-z0-9]+/g, '');
}

/*
 * Jelölt alakok – a logós táblához (logoKeyCandidates) hasonlóan: teljes
 * normalizált név, „hu” előtag nélkül, és a „spieler”→„spiler” változat.
 */
export function huEpgIdCandidates(name: string): string[] {
  const out: string[] = [];
  const push = (value: string): void => { if (value && !out.includes(value)) out.push(value); };
  const key = normalizeEpgName(name);
  push(key);
  for (const variant of [key, key.replace(/spieler/g, 'spiler')]) {
    push(variant);
    if (variant.startsWith('hu') && variant.length > 2) push(variant.slice(2));
  }
  return out;
}

/**
 * A magyar csatorna nyilvános EPG azonosítója (pl. „TV2.hu”) a beépített
 * táblából – csak magyar ([HU]) csatornákhoz használandó, a logókhoz hasonlóan.
 */
export function getHuEpgId(name: string): string | undefined {
  for (const candidate of huEpgIdCandidates(name)) {
    const hit = HU_EPG_IDS[candidate];
    if (hit) return hit;
  }
  return undefined;
}
